#!/usr/bin/env python3
"""
Prepare room photos for the website.

Usage:
    python3 tools/prepare_photos.py <folder-with-originals>

The folder must contain one sub-folder per room, named exactly like the room in the
live feed (e.g. "1", "Room 2A"). Photos inside are used in file-name order, so name
them 01.jpg, 02.jpg, ... to control the order (the first one is the cover photo).

For every photo this writes two web-sized JPEGs (800px and 1600px wide) into
photos/<room-slug>/, removes all metadata (including phone GPS location), and
regenerates assets/js/photos.js. Existing photos for rooms in the folder are replaced;
other rooms are left alone.

Requires Pillow (pip install Pillow). HEIC files additionally need pillow-heif.
"""
import json
import re
import shutil
import sys
from pathlib import Path

from PIL import Image, ImageOps

try:  # optional iPhone HEIC support
    from pillow_heif import register_heif_opener
    register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
PHOTOS_DIR = ROOT / "photos"
MANIFEST = ROOT / "assets" / "js" / "photos.js"
SIZES = (800, 1600)
EXTS = {".jpg", ".jpeg", ".png", ".webp", ".heic", ".heif"}


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.strip().lower()).strip("-")
    return s or "room"


def natural_key(p):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", p.name)]


def process_room(src_dir):
    key = slug(src_dir.name)
    out_dir = PHOTOS_DIR / key
    files = sorted((f for f in src_dir.iterdir() if f.suffix.lower() in EXTS), key=natural_key)
    if not files:
        return key, None
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    for n, f in enumerate(files, 1):
        with Image.open(f) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            for width in SIZES:
                copy = im.copy()
                if copy.width > width:
                    copy = copy.resize((width, round(copy.height * width / copy.width)), Image.LANCZOS)
                copy.save(out_dir / f"{n:02d}-{width}.jpg", "JPEG", quality=80, optimize=True, progressive=True)
        print(f"  {src_dir.name}: {f.name}")
    return key, len(files)


def build_manifest():
    data = {}
    for room_dir in sorted(p for p in PHOTOS_DIR.iterdir() if p.is_dir()):
        nums = sorted({int(m.group(1)) for f in room_dir.glob("*.jpg") if (m := re.match(r"(\d+)-\d+\.jpg$", f.name))})
        items = []
        for n in nums:
            small = room_dir / f"{n:02d}-{SIZES[0]}.jpg"
            large = room_dir / f"{n:02d}-{SIZES[1]}.jpg"
            with Image.open(small) as s:
                w, h = s.size
            with Image.open(large) as l:
                lw = l.width
            rel = lambda p: p.relative_to(ROOT).as_posix()
            items.append({
                "src": rel(small),
                "srcset": f"{rel(small)} {w}w, {rel(large)} {lw}w",
                "full": rel(large),
                "w": w,
                "h": h,
            })
        if items:
            data[room_dir.name] = items
    MANIFEST.write_text(
        "/*\n"
        " * Room photos. This file is generated by tools/prepare_photos.py — don't edit by hand.\n"
        " * Keys are the room name from the live feed, simplified (e.g. \"Room 2A\" -> \"room-2a\").\n"
        " */\n"
        "window.CQ_PHOTOS = " + json.dumps(data, indent=2) + ";\n",
        encoding="utf-8",
    )


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1]).expanduser()
    if not src.is_dir():
        sys.exit(f"Not a folder: {src}")
    PHOTOS_DIR.mkdir(exist_ok=True)
    for room_dir in sorted(p for p in src.iterdir() if p.is_dir()):
        key, count = process_room(room_dir)
        print(f"{room_dir.name} -> photos/{key}/ ({count or 0} photos)")
    build_manifest()
    print(f"Updated {MANIFEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
